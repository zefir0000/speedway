CREATE TABLE IF NOT EXISTS players (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS race_scores (
 id VARCHAR(100) CHARACTER SET ascii PRIMARY KEY,
 owner_id CHAR(36) CHARACTER SET ascii NOT NULL,
 name VARCHAR(20) NOT NULL,
 time_ms INT UNSIGNED NOT NULL,
 level VARCHAR(10) CHARACTER SET ascii NOT NULL,
 players TINYINT UNSIGNED NOT NULL,
 track VARCHAR(20) CHARACTER SET ascii NOT NULL,
 rules SMALLINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX idx_scores_track (track,rules,time_ms,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gp_campaigns (
 id VARCHAR(100) CHARACTER SET ascii PRIMARY KEY,
 owner_id CHAR(36) CHARACTER SET ascii NOT NULL,
 state LONGTEXT NOT NULL CHECK (JSON_VALID(state)),
 revision INT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX idx_campaign_owner (owner_id,updated_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS online_matches (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 track VARCHAR(20) CHARACTER SET ascii NOT NULL,
 started_at DATETIME(3) NOT NULL,
 completed_at DATETIME(3) NOT NULL,
 reason VARCHAR(20) CHARACTER SET ascii NOT NULL,
 result LONGTEXT NOT NULL CHECK (JSON_VALID(result))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS online_match_riders (
 match_id CHAR(36) CHARACTER SET ascii NOT NULL,
 gate TINYINT UNSIGNED NOT NULL,
 owner_id CHAR(36) CHARACTER SET ascii NULL,
 name VARCHAR(20) NOT NULL,
 is_bot BOOLEAN NOT NULL,
 eliminated BOOLEAN NOT NULL,
 finish_ms INT UNSIGNED NULL,
 position TINYINT UNSIGNED NOT NULL,
 PRIMARY KEY(match_id,gate),
 CONSTRAINT fk_rider_match FOREIGN KEY(match_id) REFERENCES online_matches(id) ON DELETE CASCADE
) ENGINE=InnoDB;
